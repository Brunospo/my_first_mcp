from mcp.server.mcpserver import MCPServer

from mcp_do_zero.service import decrypt, encrypt

server = MCPServer("Meu Servidor MCP")


@server.tool()
async def encrypt_message(message: str, encryption_key: str) -> str:
    """encrypt a message."""
    try:
        encrypted_message = encrypt(message, encryption_key)
        return encrypted_message
    except Exception as exc:
        return {
            "isError": True,
            "content": [
                {
                    "type": "text",
                    "text": f"Failed to encrypt message! Check if the message and encryption key are correct. Error details: {exc}",
                }
            ],
        }


@server.tool()
async def decrypt_message(encrypted_message: str, encryption_key: str) -> str:
    """decrypt message."""
    try:
        decrypted_message = decrypt(encrypted_message, encryption_key)
        return decrypted_message
    except Exception as exc:
        return {
            "isError": True,
            "content": [
                {
                    "type": "text",
                    "text": f"Failed to decrypt message! Check if the encrypted message and encryption key are correct. Error details: {exc}",
                }
            ],
        }


@server.resource(
    uri="encryption://info",
    name="Encryption Info",
    description="Describes the encryption algorithm, key requirements, and output format used by this server",
    mime_type="text/plain",
)
def get_encryption_info() -> str:
    """Retorna as informações reais baseadas na implementação do Fernet e PBKDF2."""
    return """
Algorithm : Fernet (AES-128 in CBC mode with PKCS7 padding, HMAC-SHA256 for authentication)
Key derivation: PBKDF2HMAC (passphrase + static salt "static_salt_16bytes", 100,000 iterations, SHA256) -> base64url-encoded key
Output format: Fernet token (URL-safe base64-encoded string containing timestamp, IV, ciphertext, and HMAC)
Notes:
  - Users pass any passphrase — the server derives the required key automatically using PBKDF2.
  - Fernet includes a timestamp and random IV, ensuring that encrypting the same message twice produces different outputs.
  - Use the exact same passphrase to decrypt.
  - Keep the full Fernet token string to decrypt later.
""".strip()


@server.resource(
    uri="decryption://info",
    name="Decryption Info",
    description="Describes the process, requirements, and guidelines for decrypting Fernet tokens generated by this server",
    mime_type="text/plain",
)
def get_decryption_info() -> str:
    """Returns the information and instructions for performing decryption based on the Fernet and PBKDF2 implementation."""
    return """
Algorithm : Fernet (AES-128 in CBC mode with PKCS7 padding, HMAC-SHA256 for authentication)
Key derivation: PBKDF2HMAC (passphrase + static salt "static_salt_16bytes", 100,000 iterations, SHA256) -> base64url-encoded key
Input format: Fernet token (URL-safe base64-encoded string containing timestamp, IV, ciphertext, and HMAC)
Notes:
- To successfully decrypt, you must provide the exact same passphrase used during encryption.
- Make sure to pass the complete Fernet token (including all parts generated during encryption).
- The key is derived automatically using the same PBKDF2 function with the static salt and configured number of iterations.
- If the token has been corrupted or the passphrase is incorrect, decryption will fail due to HMAC invalidation or a padding error.
""".strip()


@server.prompt(
    name="encrypt_message_prompt",
    description="Prompt to encrypt a plain-text message using the encrypt_message tool",
)
def encrypt_message_prompt(message: str, encryption_key: str) -> str:
    """
    Args:
        message: The message to encrypt
        encryption_key: Any passphrase to use for encryption — the server derives a strong key from it automatically
    """
    return f"Please encrypt the following message using the encrypt_message tool.\nMessage: {message}\nEncryption key: {encryption_key}"
